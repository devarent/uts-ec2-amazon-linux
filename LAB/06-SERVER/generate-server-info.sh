<tr><td>SSH (:22)</td><td>$( [ -n "$SSH_PORT" ] && echo '<span class="ok">SSH LISTENING</span>' || echo '<span class="bad">SSH DOWN</span>' )</td></tr>
<tr><td>Docker</td><td>$( [ "$DOCKER" = "active" ] && echo '<span class="ok">DOCKER RUNNING</span>' || echo '<span class="bad">'"$DOCKER"'</span>' )</td></tr>
<tr><td>Kubernetes (k3s)</td><td>$( [ "$K3S" = "active" ] && echo '<span class="ok">K3S RUNNING</span>' || echo '<span class="bad">'"$K3S"'</span>' )</td></tr>
</table></section>

<footer>UTS Cloud Computing · Muhammad Arya Fatthurahman · NIM 2023230006 · generated by generate-server-info.sh</footer>
</div></body></html>
