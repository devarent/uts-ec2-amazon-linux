<html lang="id">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="refresh" content="30">
<title>STATUS — ${HOST} — Muhammad Arya Fatthurahman</title>
<style>
body{font-family:Consolas,Menlo,monospace;background:#0d1117;color:#c9d1d9;margin:0;padding:24px}
.wrap{max-width:900px;margin:0 auto}
h1{color:#58a6ff;font-size:20px;margin-bottom:2px}
.sub{color:#8b949e;font-size:12px}
.card{background:#161b22;border:1px solid #2d333b;border-radius:12px;padding:16px 20px;margin-top:14px}
h2{color:#79c0ff;font-size:12px;text-transform:uppercase;letter-spacing:1.5px;margin-bottom:10px;border-bottom:1px solid #2d333b;padding-bottom:6px}
table{width:100%;border-collapse:collapse;font-size:13px}
td{padding:7px 8px;border-bottom:1px dashed #2d333b}
td:first-child{color:#8b949e;width:260px}
.ok{color:#3fb950;font-weight:700}
.bad{color:#f85149;font-weight:700}
code{color:#79c0ff}
footer{text-align:center;color:#8b949e;font-size:11px;margin-top:16px}
</style>
</head>
<body><div class="wrap">

<h1>STATUS SERVER — ${HOST}</h1>
<div class="sub">Muhammad Arya Fatthurahman · NIM 2023230006 · TIFM · UNSADA · ${DATE_NOW}</div>

<section class="card"><h2>Identitas</h2><table>
<tr><td>Hostname</td><td><code>${HOST}</code></td></tr>
<tr><td>OS / Distro</td><td>${DISTRO}</td></tr>
<tr><td>Kernel</td><td>${KERNEL}</td></tr>
<tr><td>Alamat IP</td><td><code>${IP4}</code></td></tr>
<tr><td>CPU</td><td>${CPU_CORES} core(s) — load average ${LOAD}</td></tr>
<tr><td>RAM</td><td>${MEM}</td></tr>
<tr><td>Disk (/)</td><td>${DISK}</td></tr>
<tr><td>Uptime</td><td>${UPTIME}</td></tr>
</table></section>

<section class="card"><h2>Layanan</h2><table>
