#!/usr/bin/env bash
# ======================================================================
#  generate-server-info.sh — buat halaman STATUS DINAMIS dari server
#  Jalankan di dalam VM (atau lewat SSH):
#    bash generate-server-info.sh > /usr/share/httpd/html/status.html   # Amazon Linux
#    bash generate-server-info.sh > /var/www/html/status.html          # Ubuntu
# ======================================================================
set -euo pipefail

HOST="$(hostname)"
IP4="$(hostname -I 2>/dev/null | awk '{print $1}')"
KERNEL="$(uname -sr)"
DISTRO="$(grep PRETTY_NAME /etc/os-release 2>/dev/null | cut -d= -f2 | tr -d '"')"
UPTIME="$(uptime -p 2>/dev/null || echo 'unknown')"
LOAD="$(cut -d' ' -f1-3 /proc/loadavg)"
CPU_CORES="$(nproc)"
MEM="$(free -m | awk '/Mem:/ {printf "%s MB total / %s MB used", $2, $3}')"
DISK="$(df -h / | awk 'NR==2 {print $3 " / " $2 " used (" $5 ")"}')"
DATE_NOW="$(date '+%Y-%m-%d %H:%M:%S %Z')"
HTTPD="$(systemctl is-active httpd 2>/dev/null || systemctl is-active apache2 2>/dev/null || echo unknown)"
DOCKER="$(systemctl is-active docker 2>/dev/null || docker info >/dev/null 2>&1 && echo active || echo inactive)"
K3S="$(systemctl is-active k3s 2>/dev/null || echo 'not installed')"
SSH_PORT="$(ss -tlnp 2>/dev/null | grep -o ':22\b' | head -n1 | tr -d ':')"
WEB_PORT="$(ss -tlnp 2>/dev/null | grep -o ':80\b' | head -n1 | tr -d ':')"

cat <<HTML
