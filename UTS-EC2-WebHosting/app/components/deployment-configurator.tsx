"use client";

import { useEffect, useState, type FormEvent } from "react";
import {
  Check,
  ClipboardCheck,
  CloudOff,
  Copy,
  Database,
  Download,
  FileCode2,
  Globe2,
  KeyRound,
  Server,
  ShieldCheck,
  Terminal,
} from "lucide-react";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Select } from "@/components/ui/text-field";

type DatabaseMode = "docker" | "rds";

type DeploymentConfig = {
  region: string;
  instanceType: string;
  adminIp: string;
  keyName: string;
  domainName: string;
  hostedZone: string;
  databaseMode: DatabaseMode;
};

const STORAGE_KEY = "ec2-lab-deployment-config";

const DEFAULT_CONFIG: DeploymentConfig = {
  region: "ap-southeast-3",
  instanceType: "t3.micro",
  adminIp: "",
  keyName: "",
  domainName: "",
  hostedZone: "",
  databaseMode: "docker",
};

const REGIONS = [
  ["ap-southeast-3", "Jakarta"],
  ["ap-southeast-1", "Singapore"],
  ["ap-northeast-1", "Tokyo"],
  ["us-east-1", "N. Virginia"],
];

const INSTANCE_TYPES = ["t3.micro", "t3.small", "t3.medium"];

function isIpv4(value: string) {
  const octets = value.split(".");
  return (
    octets.length === 4 &&
    octets.every((octet) => {
      if (!/^\d{1,3}$/.test(octet)) return false;
      const number = Number(octet);
      return number >= 0 && number <= 255;
    })
  );
}

function isDomain(value: string) {
  return (
    value.length <= 253 &&
    /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/i.test(
      value,
    )
  );
}

function quoteHcl(value: string) {
  return JSON.stringify(value);
}

function createTerraformVars(config: DeploymentConfig) {
  const lines = [
    "# Generated by the UTS Cloud Computing — AWS EC2 configurator.",
    "# Review this file before running Terraform. Do not put passwords here.",
    `aws_region = ${quoteHcl(config.region)}`,
    'project_name = "uts-cloud-computing"',
    'environment = "lab"',
    `instance_type = ${quoteHcl(config.instanceType)}`,
    "root_volume_size = 20",
    `ssh_cidr = ${quoteHcl(config.adminIp ? `${config.adminIp}/32` : "")}`,
  ];

  if (config.keyName.trim()) {
    lines.push(`key_name = ${quoteHcl(config.keyName.trim())}`);
  }

  if (config.domainName.trim() && config.hostedZone.trim()) {
    lines.push(`domain_name = ${quoteHcl(config.domainName.trim())}`);
    lines.push(`hosted_zone_name = ${quoteHcl(config.hostedZone.trim())}`);
  }

  if (config.databaseMode === "rds") {
    lines.push(
      "",
      "# RDS is billed separately from EC2.",
      'rds_postgres_version = "15.4"',
      'rds_instance_class = "db.t3.micro"',
      "rds_allocated_storage = 20",
      'rds_database_name = "ec2lab"',
      'rds_master_username = "ec2lab_admin"',
      "rds_deletion_protection = true",
      "rds_skip_final_snapshot = false",
    );
  }

  return `${lines.join("\n")}\n`;
}

function createReviewNotes(databaseMode: DatabaseMode) {
  const lines = [
    "# Checklist pemeriksaan lokal dari WSL2; tidak membuat resource AWS.",
    "# Unduh terraform.tfvars, lalu tinjau region, IP SSH, dan pilihan database.",
    "# Pastikan folder Terraform memakai provider dan variabel yang sesuai.",
    "# Tidak ada perintah terraform apply pada lab ini.",
  ];
  lines.push(
    "",
    "# Jika nanti ingin provisioning, tinjau requirement dan minta persetujuan",
    "# sebelum menjalankan perintah Terraform yang mengubah resource.",
    "",
    `# Mode database terpilih: ${databaseMode === "rds" ? "AWS RDS (biaya terpisah)" : "PostgreSQL dalam Docker"}`,
  );

  if (databaseMode === "rds") {
    lines.push(
      "",
      "# Catatan: rencanakan subnet privat, security group, backup, dan biaya RDS.",
      "# Jangan menyimpan password database di file konfigurasi ini.",
    );
  } else {
    lines.push(
      "",
      "# Catatan: PostgreSQL memakai volume persisten; port 5432 tetap internal.",
    );
  }

  return `${lines.join("\n")}\n`;
}

export default function DeploymentConfigurator() {
  const [config, setConfig] = useState(DEFAULT_CONFIG);
  const [terraformVars, setTerraformVars] = useState("");
  const [reviewNotes, setReviewNotes] = useState("");
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");
  const [copied, setCopied] = useState<"vars" | "review" | null>(null);

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved) as Partial<DeploymentConfig>;
        setConfig({ ...DEFAULT_CONFIG, ...parsed });
      }
    } catch (storageError) {
      console.error(
        "Could not load the saved deployment configuration.",
        storageError,
      );
      setError("Konfigurasi tersimpan tidak dapat dibaca. Isi ulang lalu coba lagi.");
    }
  }, []);

  function update<K extends keyof DeploymentConfig>(
    key: K,
    value: DeploymentConfig[K],
  ) {
    setConfig((current) => ({ ...current, [key]: value }));
    setNotice("");
  }

  function saveConfiguration(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setError("");
    setNotice("");
    setCopied(null);

    const ip = config.adminIp.trim();
    if (!ip) {
      setError("Isi IPv4 publik admin agar akses SSH dibatasi ke alamat kamu.");
      return;
    }
    if (!isIpv4(ip)) {
      setError("Masukkan IPv4 saja (contoh: 203.0.113.10), tanpa /32.");
      return;
    }
    if (!config.keyName.trim()) {
      setError(
        "Masukkan nama key pair RSA yang sudah tersedia di AWS Region terpilih.",
      );
      return;
    }

    const domainName = config.domainName.trim();
    const hostedZone = config.hostedZone.trim();
    if (Boolean(domainName) !== Boolean(hostedZone)) {
      setError("Isi domain aplikasi dan hosted zone sekaligus, atau kosongkan keduanya.");
      return;
    }
    if (
      (domainName && !isDomain(domainName)) ||
      (hostedZone && !isDomain(hostedZone))
    ) {
      setError("Format domain tidak valid. Contoh: app.example.com.");
      return;
    }
    if (
      domainName &&
      domainName.toLowerCase() !== hostedZone.toLowerCase() &&
      !domainName.toLowerCase().endsWith(`.${hostedZone.toLowerCase()}`)
    ) {
      setError("Domain aplikasi harus sama dengan atau berada di bawah hosted zone.");
      return;
    }

    try {
      window.localStorage.setItem(STORAGE_KEY, JSON.stringify(config));
      setTerraformVars(createTerraformVars(config));
      setReviewNotes(createReviewNotes(config.databaseMode));
      setNotice(
        "Konfigurasi disimpan di browser ini. Belum ada resource AWS yang dibuat.",
      );
    } catch (storageError) {
      console.error("Could not save the deployment configuration.", storageError);
      setError(
        "Konfigurasi gagal disimpan di browser. Periksa ruang penyimpanan lalu coba lagi.",
      );
    }
  }

  async function copyText(value: string, type: "vars" | "review") {
    try {
      await navigator.clipboard.writeText(value);
      setCopied(type);
      setNotice("Berhasil disalin ke clipboard.");
    } catch (clipboardError) {
      console.error("Could not copy deployment configuration.", clipboardError);
      setError(
        "Clipboard tidak tersedia. Pilih dan salin teks konfigurasi secara manual.",
      );
    }
  }

  function downloadTerraformVars() {
    const blob = new Blob([terraformVars], {
      type: "text/plain;charset=utf-8",
    });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = "terraform.tfvars";
    anchor.click();
    URL.revokeObjectURL(url);
  }

  return (
    <section
      id="konfigurasi"
      className="scroll-mt-32 border-y border-border bg-muted/30"
    >
      <div className="mx-auto w-full max-w-7xl px-4 py-16 sm:px-6 sm:py-20 lg:px-8">
        <div className="flex flex-col justify-between gap-5 md:flex-row md:items-end">
          <div className="max-w-3xl">
            <p className="font-mono text-[11px] font-semibold uppercase tracking-[0.18em] text-muted-foreground">
              04 · Konfigurasi lokal
            </p>
            <h2 className="mt-3 text-3xl font-semibold tracking-tight text-foreground sm:text-4xl">
              Rancang pilihan EC2 dan database.
            </h2>
            <p className="mt-3 text-sm leading-6 text-muted-foreground sm:text-base">
              Pilih PostgreSQL dalam Docker untuk jalur UTS atau RDS privat
              sebagai opsi terkelola. Form ini hanya menyimpan pilihan di browser
              dan menyiapkan file untuk ditinjau.
            </p>
          </div>
          <div className="flex flex-wrap gap-2">
            <Badge variant="success">
              <ShieldCheck className="size-3" />
              Tanpa AWS API
            </Badge>
            <Badge variant="outline" className="bg-card">
              <CloudOff className="size-3" />
              Tidak membuat resource
            </Badge>
          </div>
        </div>

        <div className="mt-8 grid gap-6 lg:grid-cols-[0.92fr_1.08fr]">
          <Card className="min-w-0 gap-0">
            <CardHeader className="border-b border-border">
              <CardTitle className="flex items-center gap-2 text-sm">
                <Server className="size-4 text-muted-foreground" />
                Parameter deployment
              </CardTitle>
              <CardDescription className="text-xs">
                Disimpan di browser ini. Tidak ada kredensial yang diminta.
              </CardDescription>
            </CardHeader>
            <CardContent className="pt-6">
              <form onSubmit={saveConfiguration} className="space-y-5">
                <div className="space-y-2">
                  <Label htmlFor="database-mode" className="gap-1.5">
                    <Database className="size-3.5 text-muted-foreground" />
                    Database
                  </Label>
                  <Select
                    id="database-mode"
                    value={config.databaseMode}
                    onChange={(event) =>
                      update("databaseMode", event.target.value as DatabaseMode)
                    }
                  >
                    <option value="docker">Docker PostgreSQL 17 — satu EC2</option>
                    <option value="rds">AWS RDS PostgreSQL — biaya terpisah</option>
                  </Select>
                  <p className="text-[11px] leading-5 text-muted-foreground">
                    {config.databaseMode === "docker"
                      ? "Rekomendasi UTS: data tetap persisten di volume Docker db-data dan port 5432 tidak dipublikasikan."
                      : "RDS dibuat di subnet privat, hanya menerima koneksi dari security group EC2. Kata sandi diminta di terminal WSL2 dan tidak disimpan di browser."}
                  </p>
                </div>

                <div className="grid gap-4 sm:grid-cols-2">
                  <div className="space-y-2">
                    <Label htmlFor="aws-region" className="gap-1.5">
                      <Globe2 className="size-3.5 text-muted-foreground" />
                      AWS Region
                    </Label>
                    <Select
                      id="aws-region"
                      value={config.region}
                      onChange={(event) => update("region", event.target.value)}
                    >
                      {REGIONS.map(([region, label]) => (
                        <option key={region} value={region}>
                          {label} ({region})
                        </option>
                      ))}
                    </Select>
                  </div>
                  <div className="space-y-2">
                    <Label htmlFor="instance-type" className="gap-1.5">
                      <Server className="size-3.5 text-muted-foreground" />
                      EC2 instance
                    </Label>
                    <Select
                      id="instance-type"
                      value={config.instanceType}
                      onChange={(event) => update("instanceType", event.target.value)}
                    >
                      {INSTANCE_TYPES.map((instanceType) => (
                        <option key={instanceType} value={instanceType}>
                          {instanceType}
                        </option>
                      ))}
                    </Select>
                  </div>
                </div>

                <div className="space-y-2">
                  <Label htmlFor="admin-ip">IP publik admin untuk SSH</Label>
                  <div className="flex rounded-lg border border-input bg-background shadow-xs transition focus-within:border-ring focus-within:ring-2 focus-within:ring-ring/20">
                    <input
                      id="admin-ip"
                      inputMode="decimal"
                      autoComplete="off"
                      value={config.adminIp}
                      onChange={(event) => update("adminIp", event.target.value)}
                      placeholder="203.0.113.10"
                      className="min-h-10 min-w-0 flex-1 rounded-l-lg bg-transparent px-3 py-2 text-sm text-foreground outline-none placeholder:text-muted-foreground/70"
                    />
                    <span className="flex items-center border-l border-border px-3 font-mono text-xs text-muted-foreground">
                      /32
                    </span>
                  </div>
                  <p className="text-[11px] leading-5 text-muted-foreground">
                    Isi IPv4 publik yang dipakai untuk SSH; wizard menambahkan
                    /32. Elastic IP EC2 dialokasikan otomatis dan berbeda dari IP
                    ini.
                  </p>
                </div>

                <div className="space-y-2">
                  <Label htmlFor="key-name" className="gap-1.5">
                    <KeyRound className="size-3.5 text-muted-foreground" />
                    Nama key pair RSA AWS
                  </Label>
                  <Input
                    id="key-name"
                    value={config.keyName}
                    onChange={(event) => update("keyName", event.target.value)}
                    maxLength={255}
                    placeholder="awskeypair"
                    required
                  />
                  <p className="text-[11px] leading-5 text-muted-foreground">
                    Buat key pair RSA terlebih dahulu di region yang dipilih, lalu
                    masukkan namanya di sini.
                  </p>
                </div>

                <div className="grid gap-4 sm:grid-cols-2">
                  <div className="space-y-2">
                    <Label htmlFor="app-domain">Domain aplikasi (opsional)</Label>
                    <Input
                      id="app-domain"
                      value={config.domainName}
                      onChange={(event) => update("domainName", event.target.value)}
                      placeholder="app.example.com"
                    />
                  </div>
                  <div className="space-y-2">
                    <Label htmlFor="hosted-zone">Route 53 hosted zone</Label>
                    <Input
                      id="hosted-zone"
                      value={config.hostedZone}
                      onChange={(event) => update("hostedZone", event.target.value)}
                      placeholder="example.com"
                    />
                  </div>
                </div>

                {error ? (
                  <Alert variant="destructive" className="py-3">
                    <AlertDescription>{error}</AlertDescription>
                  </Alert>
                ) : null}
                {notice ? (
                  <Alert variant="success" className="py-3">
                    <Check />
                    <AlertDescription>{notice}</AlertDescription>
                  </Alert>
                ) : null}

                <Button type="submit" size="lg" className="w-full">
                  <FileCode2 />
                  Simpan pilihan &amp; siapkan berkas
                </Button>
                <p className="rounded-lg border border-border bg-muted/40 p-3 text-[11px] leading-5 text-muted-foreground">
                  Tidak ada koneksi ke AWS dan tidak ada resource yang dibuat.
                  Tinjau file hasil secara manual sebelum menggunakannya di luar
                  aplikasi.
                </p>
              </form>
            </CardContent>
          </Card>

          <div className="min-w-0 space-y-5">
            <Card className="gap-0">
              <CardHeader className="border-b border-border py-4">
                <div className="flex flex-wrap items-center justify-between gap-3">
                  <div>
                    <p className="font-mono text-[10px] font-semibold uppercase tracking-[0.16em] text-muted-foreground">
                      terraform.tfvars
                    </p>
                    <CardTitle className="mt-1 text-sm">Pratinjau konfigurasi</CardTitle>
                  </div>
                  {terraformVars ? (
                    <div className="flex gap-2">
                      <Button
                        type="button"
                        variant="outline"
                        size="sm"
                        onClick={() => void copyText(terraformVars, "vars")}
                      >
                        <Copy />
                        {copied === "vars" ? "Tersalin" : "Salin"}
                      </Button>
                      <Button
                        type="button"
                        variant="outline"
                        size="sm"
                        onClick={downloadTerraformVars}
                      >
                        <Download />
                        Unduh
                      </Button>
                    </div>
                  ) : null}
                </div>
              </CardHeader>
              <CardContent className="pt-5">
                <pre className="scrollbar-thin min-h-40 overflow-x-auto rounded-xl border border-zinc-800 bg-zinc-950 p-4 font-mono text-[11px] leading-relaxed text-zinc-200 sm:text-xs">
                  {terraformVars ||
                    "# Isi pilihan di formulir, lalu simpan untuk melihat pratinjau."}
                </pre>
                <p className="mt-3 text-[11px] leading-5 text-muted-foreground">
                  File ini berisi region, tipe EC2, pembatasan SSH, dan pilihan
                  database. Password RDS tidak pernah dimasukkan ke dalamnya.
                </p>
              </CardContent>
            </Card>

            <Card className="gap-0">
              <CardHeader className="border-b border-border py-4">
                <div className="flex flex-wrap items-center justify-between gap-3">
                  <div>
                    <p className="font-mono text-[10px] font-semibold uppercase tracking-[0.16em] text-muted-foreground">
                      Panduan tinjauan
                    </p>
                    <CardTitle className="mt-1 text-sm">
                      Periksa sebelum langkah berikutnya
                    </CardTitle>
                  </div>
                  {reviewNotes ? (
                    <Button
                      type="button"
                      variant="outline"
                      size="sm"
                      onClick={() => void copyText(reviewNotes, "review")}
                    >
                      <ClipboardCheck />
                      {copied === "review" ? "Tersalin" : "Salin"}
                    </Button>
                  ) : null}
                </div>
              </CardHeader>
              <CardContent className="pt-5">
                <pre className="scrollbar-thin min-h-40 overflow-x-auto rounded-xl border border-zinc-800 bg-zinc-950 p-4 font-mono text-[11px] leading-relaxed text-zinc-200 sm:text-xs">
                  {reviewNotes ||
                    "# Daftar tinjauan muncul setelah pilihan disimpan."}
                </pre>
                <Alert variant="warning" className="mt-3 py-3">
                  <Terminal />
                  <AlertDescription className="text-xs">
                    Ini hanya bahan tinjauan. Tidak ada perintah apply, tidak ada
                    resource yang dibuat, dan password database tidak disimpan.
                  </AlertDescription>
                </Alert>
              </CardContent>
            </Card>
          </div>
        </div>
      </div>
    </section>
  );
}
